'use strict';
const router = require('express').Router();
const { authenticateToken } = require('./auth');
const chat = require('../controllers/chatController');
const multer = require('multer');
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 20 * 1024 * 1024 } });
router.use(authenticateToken);
router.get('/people', chat.listPeople);
router.get('/conversations', chat.listConversations);
router.post('/conversations/direct', chat.openDirect);
router.post('/conversations/group', chat.createGroup);
router.get('/conversations/:id/messages', chat.messages);
router.get('/conversations/:id/search', chat.search);
router.get('/conversations/:id/pins', chat.pins);
router.post('/conversations/:id/pins/:messageId', chat.pin);
router.delete('/conversations/:id/pins/:messageId', chat.unpin);
router.get('/conversations/:id/attendance-summary', chat.attendanceSummary);
router.get('/conversations/:id/dial', chat.dial);
router.post('/conversations/:id/delivered', chat.markDelivered);
router.get('/conversations/:id/attachments', chat.attachments);
router.post('/conversations/:id/messages', chat.send);
router.post('/conversations/:id/attachments', upload.single('file'), chat.uploadAttachment);
router.post('/conversations/:id/read', chat.markRead);
router.put('/conversations/:id/mute', chat.mute);
router.post('/push-tokens', chat.registerPushToken);
module.exports = router;
